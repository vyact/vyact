def code_message(key: str, **params) -> str:
    language = (_current_language.get() or "en").replace("_", "-").split("-", 1)[0].lower()
    return MESSAGES.get(language, MESSAGES["en"])[key].format(**params)


def code_error(key: str, **params) -> str:
    return tool_error(code_message(key, **params))


def localized_code_tool(handler):
    @wraps(handler)
    async def wrapped(*args, **kwargs):
        if _current_language.get() is not None:
            return await handler(*args, **kwargs)
        token = _current_language.set(await get_tool_language())
        try:
            return await handler(*args, **kwargs)
        finally:
            _current_language.reset(token)
    return wrapped
