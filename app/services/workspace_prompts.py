WORKSPACE_HEADERS = {'google_workspace': 'Google Workspace (Gmail, Calendar, Drive, Docs, Sheets, Slides, Forms)',
 'microsoft_workspace': 'Microsoft 365 (Outlook, Calendar, OneDrive)'}


def get_workspace_prompt(provider: str, language: str) -> str:
    header = WORKSPACE_HEADERS.get(provider)
    if not header:
        return ""
    code = (language or "en").replace("_", "-").split("-", 1)[0].lower()
    rules = WORKSPACE_RULES.get(code, WORKSPACE_RULES["en"])
    return f"{header}\n\n{rules}"
